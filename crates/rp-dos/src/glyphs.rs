#[cfg(test)]
mod tests {
    use super::*;

    fn all_icons() -> [Icon; 10] {
        [
            ICON_SELECT,
            ICON_MOVE,
            ICON_BRUSH,
            ICON_ERASER,
            ICON_PICKER,
            ICON_FILL,
            ICON_LINE,
            ICON_RECT,
            ICON_ELLIPSE,
            ICON_TEXT,
        ]
    }

    #[test]
    fn icons_are_12_by_12() {
        for icon in all_icons() {
            for row in icon {
                assert_eq!(row.len(), ICON_SIZE as usize, "{row:?}");
            }
        }
    }

    #[test]
    fn arrow_rows_are_equal_width() {
        assert!(ARROW.iter().all(|r| r.len() == ARROW[0].len()));
    }

    #[test]
    fn glyphs_fit_three_bits_and_text_width() {
        for c in ('A'..='Z').chain('0'..='9') {
            let g = glyph(c);
            assert!(g.iter().all(|&r| r < 8), "{c}");
            assert!(g.iter().any(|&r| r != 0), "{c} is blank");
        }
        assert_eq!(text_width(""), 0);
        assert_eq!(text_width("AB"), 7);
    }
}
